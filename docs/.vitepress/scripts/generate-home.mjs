// Generates docs/home-zh.md as a build-time copy of docs/zh/index.md.
// It is mapped via `rewrites` (see .vitepress/config.ts) to the site root
// `index.md`, so the Chinese homepage also renders at `/` without moving
// or aliasing the original `index.md` (English) or `zh/index.md` sources.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const docsRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const src = join(docsRoot, 'zh/index.md')
const dest = join(docsRoot, 'home-zh.md')

const banner = '<!-- AUTO-GENERATED by .vitepress/scripts/generate-home.mjs — do not edit. Source: zh/index.md -->\n'
writeFileSync(dest, banner + readFileSync(src, 'utf-8'))
